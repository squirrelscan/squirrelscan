// White-label report branding (#810): Team orgs render reports without
// squirrelscan branding, using their own logo (or name) in the header. These
// pin the on/off behaviour for every renderer; the "off" path must stay
// byte-identical to the default branded output.

import { describe, expect, test } from "bun:test";

import type { ReportBranding } from "@squirrelscan/core-contracts";
import type { AuditReport } from "../src/types";
import { REPORT_HTML_VERSION } from "../src/constants";
import { renderHtml } from "../src/output/html";
import { renderMarkdown } from "../src/output/markdown";
import { renderText } from "../src/output/text";
import { renderXml } from "../src/output/xml";

function baseReport(overrides: Partial<AuditReport> = {}): AuditReport {
  return {
    baseUrl: "https://acme.example",
    timestamp: "2026-06-16T14:30:00.000Z",
    totalPages: 1,
    passed: 0,
    warnings: 0,
    failed: 0,
    ruleResults: {},
    generatorVersion: "1.2.3",
    lockedRules: [{ id: "a", name: "Locked Check" }],
    ...overrides,
  };
}

const WHITE_LABEL: ReportBranding = {
  whiteLabel: true,
  orgLogoUrl: "https://api.squirrelscan.com/v1/organizations/org_1/logo?v=1",
  orgName: "Acme Inc",
};

describe("white-label html", () => {
  test("default (no branding) keeps squirrelscan logo, footer, and og:site_name", () => {
    const html = renderHtml(baseReport(), { reportId: "r1" });
    expect(html).toContain("squirrelscan");
    expect(html).toContain('href="https://squirrelscan.com"');
    expect(html).toContain("Generated by");
    expect(html).toContain('content="squirrelscan"');
  });

  test("white-label hides squirrelscan wordmark, footer credit, and CTA", () => {
    const html = renderHtml(baseReport(), { reportId: "r1", branding: WHITE_LABEL });
    // No squirrelscan wordmark link or "Generated by" credit.
    expect(html).not.toContain('href="https://squirrelscan.com"');
    expect(html).not.toContain("Generated by");
    // The locked-rules upsell / account CTA is dropped entirely.
    expect(html).not.toContain('id="locked-rules"');
    expect(html).not.toContain('id="cloud"');
    // og:site_name uses the org name, not squirrelscan.
    expect(html).toContain('property="og:site_name" content="Acme Inc"');
    expect(html).not.toContain('content="squirrelscan"');
  });

  test("white-label shows the org logo when set", () => {
    const html = renderHtml(baseReport(), { branding: WHITE_LABEL });
    expect(html).toContain(WHITE_LABEL.orgLogoUrl as string);
    expect(html).toMatch(/<img [^>]*class="wl-logo /);
  });

  test("white-label falls back to the org name as plain text when no logo", () => {
    const html = renderHtml(baseReport(), {
      branding: { whiteLabel: true, orgName: "Acme Inc" },
    });
    expect(html).toContain('class="wl-wordmark ');
    expect(html).toContain("Acme Inc");
    expect(html).not.toContain("wl-logo");
  });
});

describe("white-label markdown", () => {
  test("default keeps the squirrelscan header and generated-by footer", () => {
    const md = renderMarkdown(baseReport(), { version: "1.2.3" });
    expect(md).toContain("# squirrelscan Audit Report");
    expect(md).toContain("Generated by [squirrelscan]");
  });

  test("white-label drops the squirrelscan header and footer", () => {
    const md = renderMarkdown(baseReport(), { version: "1.2.3", branding: WHITE_LABEL });
    expect(md).not.toContain("squirrelscan");
    expect(md).toContain("# Acme Inc Audit Report");
    expect(md).not.toContain("Generated by");
  });
});

describe("white-label text + xml", () => {
  test("text default vs white-label", () => {
    expect(renderText(baseReport())).toContain("Generated by squirrelscan.com");
    const wl = renderText(baseReport(), { branding: WHITE_LABEL });
    expect(wl).not.toContain("squirrelscan");
    expect(wl).toContain("Acme Inc");
  });

  test("xml uses a neutral root element when white-label", () => {
    expect(renderXml(baseReport())).toContain("<squirrelscan-audit");
    const wl = renderXml(baseReport(), { branding: WHITE_LABEL });
    expect(wl).not.toContain("squirrelscan");
    expect(wl).toContain("<audit ");
    expect(wl).toContain("</audit>");
  });
});

// #3176: the org's website link and footer text, from its white-label settings.
describe("white-label website link and footer text", () => {
  const BRANDED: ReportBranding = {
    ...WHITE_LABEL,
    websiteUrl: "https://acme.example/",
    footerText: "© 2026 Acme Inc. Prepared for our clients.",
  };

  test("html links the logo to the website, in a new tab without an opener", () => {
    const html = renderHtml(baseReport(), { branding: BRANDED });
    expect(html).toMatch(
      /<a href="https:\/\/acme\.example\/" target="_blank" rel="noopener noreferrer" class="wl-brand-link"><img [^>]*class="wl-logo /,
    );
  });

  test("html links the name when there is no logo", () => {
    const html = renderHtml(baseReport(), {
      branding: { whiteLabel: true, orgName: "Acme Inc", websiteUrl: "https://acme.example/" },
    });
    expect(html).toMatch(/<a href="https:\/\/acme\.example\/"[^>]*><span class="wl-wordmark /);
  });

  test("html links only an https website", () => {
    for (const websiteUrl of ["javascript:alert(1)", "http://acme.example/", "//acme.example"]) {
      const html = renderHtml(baseReport(), { branding: { ...WHITE_LABEL, websiteUrl } });
      expect(html).not.toContain("wl-brand-link");
      expect(html).toMatch(/<img [^>]*class="wl-logo /);
    }
  });

  test("html shows the footer text and website link in place of the squirrelscan credit", () => {
    const html = renderHtml(baseReport(), { branding: BRANDED });
    expect(html).toMatch(
      /<span class="wl-footer">© 2026 Acme Inc\. Prepared for our clients\. · <a href="https:\/\/acme\.example\/" target="_blank" rel="noopener noreferrer" class="lnk wl-footer-link">acme\.example<\/a><\/span>/,
    );
    expect(html).not.toContain("Generated by");

    const textOnly = renderHtml(baseReport(), {
      branding: { ...WHITE_LABEL, footerText: "© Acme" },
    });
    expect(textOnly).toContain('<span class="wl-footer">© Acme</span>');
    const linkOnly = renderHtml(baseReport(), {
      branding: { ...WHITE_LABEL, websiteUrl: "https://acme.example/" },
    });
    expect(linkOnly).toMatch(
      /<span class="wl-footer"><a href="https:\/\/acme\.example\/"[^>]*>acme\.example<\/a><\/span>/,
    );
    const insecure = renderHtml(baseReport(), {
      branding: { ...WHITE_LABEL, websiteUrl: "http://acme.example/" },
    });
    expect(insecure).not.toContain("wl-footer");

    const hostile = renderHtml(baseReport(), {
      branding: { ...WHITE_LABEL, footerText: '<img src=x onerror="alert(1)">' },
    });
    expect(hostile).toContain("&lt;img src=x onerror=");
    expect(hostile).not.toContain('<img src=x onerror="alert(1)">');
  });

  test("a default report ignores the white-label fields", () => {
    const html = renderHtml(baseReport(), {
      branding: { ...BRANDED, whiteLabel: false },
    });
    expect(html).toContain("Generated by");
    expect(html).not.toContain("wl-footer");
    expect(html).not.toContain("wl-brand-link");
  });

  test("markdown and text end with the footer text and the website", () => {
    const md = renderMarkdown(baseReport(), { branding: BRANDED });
    expect(md.trimEnd().split("\n").at(-1)).toBe(
      "© 2026 Acme Inc. Prepared for our clients. · <https://acme.example/>",
    );
    expect(md).not.toContain("Generated by");
    const text = renderText(baseReport(), { branding: BRANDED }).trimEnd().split("\n");
    expect(text.slice(-2)).toEqual([
      "© 2026 Acme Inc. Prepared for our clients.",
      "https://acme.example/",
    ]);
  });

  test("REPORT_HTML_VERSION is bumped for the new header link and footer markup", () => {
    expect(REPORT_HTML_VERSION).toBeGreaterThanOrEqual(21);
  });

  test("markdown escapes the brand name and footer text", () => {
    const md = renderMarkdown(baseReport(), {
      branding: {
        whiteLabel: true,
        orgName: "Acme [click](javascript:alert(1))",
        footerText: "**bold** [x](https://evil.example)",
      },
    });
    expect(md).toContain("# Acme \\[click\\]\\(javascript:alert\\(1\\)\\) Audit Report");
    expect(md).toContain("\\*\\*bold\\*\\* \\[x\\]\\(https://evil.example\\)");
  });

  test("a markdown footer that starts like a block (list, heading, number) stays text", () => {
    for (const [footerText, line] of [
      ["- Prepared by Acme", "\\- Prepared by Acme"],
      ["# Acme", "\\# Acme"],
      ["1. Acme", "1\\. Acme"],
    ]) {
      const md = renderMarkdown(baseReport(), { branding: { ...WHITE_LABEL, footerText } });
      expect(md.trimEnd().split("\n").at(-1)).toBe(line);
    }
  });
});
