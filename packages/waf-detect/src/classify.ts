import type { HeaderBag, WafBlockProvider, WafBlockResult, WafResponse } from "./types";
import {
  AKAMAI_REFERENCE_ID,
  CLOUDFLARE_CHALLENGE_SCRIPT,
  DASH,
  IMPERVA_INCIDENT_LINE,
  WAF_BLOCK_STATUS_CODES,
  WAF_CHALLENGE_STATUS_CODES,
  getWafProviderName,
} from "./providers";
import { detectWafFromHeaders } from "./detect";
import { signatureViews } from "./views";
import { visibleTextLength } from "./visible-text";

/**
 * How much of a body is read for signatures. A block page is small or carries
 * its marker in the head; a hostile 1 MB body costs one linear pass over this
 * prefix and nothing more.
 */
const SCAN_BYTES = 32_768;

/** Cloudflare's own block page is about 30 KB (inline CSS); nothing here is larger than this. */
const MAX_INTERSTITIAL_BYTES = 100_000;

/** Visible-text ceiling for a page that is only an interstitial (heading, widget, one line). */
const INTERSTITIAL_TEXT = 600;
/** A deny page is a heading, a sentence and a reference line. */
const DENY_PAGE_TEXT = 800;
/** A script-only JS challenge page has no words at all. */
const EMPTY_PAGE_TEXT = 60;

/** The scheme-or-protocol-relative start of a URL, so a host is matched where it is loaded from. */
const URL_START = String.raw`\s*=\s*["']?(?:https?:)?\/\/`;
/** The end of a registrable host: not followed by more host (`captcha-delivery.com.attacker.example`). */
const HOST_END = String.raw`(?![\w-]|\.[\w-])`;

const DATADOME_HOST = new RegExp(
  `(?:src|href|action)${URL_START}(?:[a-z0-9-]{1,63}\\.){0,3}captcha-delivery\\.com${HOST_END}`,
  "i",
);
// DataDome's inline config: `var dd={'rt':'c','cid':'...','hsh':'...','host':'geo.captcha-delivery.com'}`.
const DATADOME_CONFIG = /\bvar\s+dd\s*=\s*\{[^}]{0,512}?['"]cid['"]\s*:/;
const PERIMETERX_MARKER = /\b_pxAppId\b|\b_pxUuid\b|\bpxCaptchaSrc\b|px-captcha/;
const PERIMETERX_APP_ID = /\b_pxAppId\b|<meta\s[^>]{0,200}name\s*=\s*["']?pxAppId/i;
const PERIMETERX_CAPTCHA_ELEMENT = /\bid\s*=\s*["']?px-captcha\b|\b_pxOnCaptchaSuccess\b/;
const KASADA_MARKER =
  /\bwindow\.KPSDK\s*=|\bKPSDK\.(?:now|start|configure)\b|\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/ips\.js\b/i;
const AWS_WAF_SCRIPT = new RegExp(
  `src${URL_START}[\\w.-]{1,128}\\.token\\.awswaf\\.com${HOST_END}|\\bAwsWaf(?:Integration|Captcha)\\b|\\bgokuProps\\b`,
  "i",
);
const RADWARE_HOST = new RegExp(
  `(?:src|href|action)${URL_START}(?:[a-z0-9-]{1,63}\\.){0,3}perfdrive\\.com${HOST_END}`,
  "i",
);
const IMPERVA_SCRIPT = /src\s*=\s*["']?\/_Incapsula_Resource\?SWJIYLWA=/i;
const IMPERVA_PARDON_TITLE = /pardon our interruption/i;
const IMPERVA_PARDON_BODY =
  /something about your browser made us think you were a bot|think you were a bot/i;
const F5_REJECTED = /the requested url was rejected\.?\s*please consult with your administrator/i;
const F5_SUPPORT_ID = /your support id is\s*:?\s*(?:<[^>]{0,64}>\s*){0,3}\d{6,}/i;
const SUCURI_BLOCK = [
  new RegExp(
    `sucuri website ?firewall\\s*${DASH}\\s*(?:cloudproxy\\s*${DASH}\\s*)?access denied`,
    "i",
  ),
  new RegExp(`access denied\\s*${DASH}\\s*sucuri website ?firewall`, "i"),
];
const WORDFENCE_HEADING =
  /your access to this site has been limited|a potentially unsafe operation has been detected in your request to this site/i;
const WORDFENCE_FOOTER = /generated by wordfence/i;
// The footer's inline script fills in "Your computer's time" (a site that only copies the
// wording does not copy it). Read in the markup view, so a page that prints the code is not matched.
const WORDFENCE_TIME_SCRIPT = /document\.write\(\s*new Date\(\)\.toUTCString\(\)\s*\)/;
const AKAMAI_DENY_TITLE = /access denied/i;
const AKAMAI_ENTITY_REFERENCE = /reference&#32;&#35;\s*\d/i;
const VERCEL_CHECKPOINT = /vercel security checkpoint/i;
const CLOUDFLARE_BLOCK_TITLE = /attention required!? ?\| ?cloudflare/i;
const CLOUDFLARE_BLOCK_MARKER = /cf-error-details/i;
const CLOUDFLARE_RAY_LINE = /cloudflare ray id:?\s*(?:<[^>]{0,64}>\s*){0,3}[0-9a-f]{6,}\b/i;
const CLOUDFLARE_CHALLENGE_MARKUP = [
  CLOUDFLARE_CHALLENGE_SCRIPT,
  /\b_cf_chl_opt\b/,
  /\b__cf_chl_/,
  /cf-browser-verification/i,
];
const REFUSAL_WORDING =
  /\b(?:access denied|forbidden|request (?:blocked|rejected|unsuccessful)|you have been blocked|you are blocked|blocked)\b/i;

function headerValue(bag: HeaderBag | null | undefined, name: string): string | null {
  if (!bag) return null;
  if (bag instanceof Headers) return bag.get(name);
  const value = bag[name];
  return typeof value === "string" ? value : null;
}

/** What each rule can ask of the response; the body is read once, and only when a rule needs it. */
interface Probe {
  status: number;
  header(name: string): string | null;
  markup(): string;
  text(): string;
  /** Visible text no longer than `limit` (a near-empty interstitial, not a page). */
  smallerThan(limit: number): boolean;
}

interface Rule {
  provider: WafBlockProvider;
  signal: string;
  applies(p: Probe): boolean;
}

const isStatus = (p: Probe, codes: ReadonlySet<number>): boolean => codes.has(p.status);

/**
 * The refusal statuses: WAF_BLOCK_STATUS_CODES without 200. A marker that is a
 * script or a mount point (a sensor snippet, a captcha widget, a script-only
 * page) is only a block when the status refuses too: at 200 a real page, an app
 * shell or a form can carry the same markup. A 200 is a block only on wording
 * no ordinary page prints (an Akamai deny reference, an incident id).
 */
const REFUSAL_STATUS_CODES: ReadonlySet<number> = new Set([...WAF_BLOCK_STATUS_CODES].filter((code) => code !== 200));

/**
 * The block and challenge shapes a perimeter provider serves, most specific
 * provider first (a bot manager behind Cloudflare is the bot manager). Each rule
 * is a provider-specific marker, read where it acts, plus whichever of a status
 * and a near-empty body it needs to rule out an ordinary page on the same
 * provider. Never a vendor's name on its own.
 *
 * Verified against live responses (2026-10-29): Cloudflare (`cf-mitigated`,
 * "Attention Required!" block page), Akamai deny (403 and 200), DataDome
 * (`var dd=`), HUMAN/PerimeterX (`x-px-blocked`, block page), Kasada (429).
 * Documented by the vendor: AWS WAF (`x-amzn-waf-action`, 202 and 405).
 * Reported by site owners in public forums: Vercel (`x-vercel-mitigated`,
 * "Vercel Security Checkpoint"), F5 ("The requested URL was rejected"),
 * Wordfence, Imperva's interstitials. Radware's host is recalled, not seen.
 */
const RULES: readonly Rule[] = [
  {
    provider: "datadome",
    signal: "DataDome challenge on a near-empty page",
    applies: (p) =>
      isStatus(p, WAF_BLOCK_STATUS_CODES) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      (DATADOME_HOST.test(p.markup()) || DATADOME_CONFIG.test(p.markup())),
  },
  {
    provider: "perimeterx",
    signal: "x-px-blocked header",
    applies: (p) => p.status >= 400 && p.header("x-px-blocked") !== null,
  },
  {
    provider: "perimeterx",
    signal: 'HUMAN block page ("Access to this page has been denied")',
    applies: (p) =>
      isStatus(p, WAF_BLOCK_STATUS_CODES) &&
      /access to this page has been denied/i.test(p.text()) &&
      PERIMETERX_MARKER.test(p.markup()),
  },
  {
    provider: "perimeterx",
    signal: "HUMAN captcha element on a challenge page",
    // A branded challenge page (a site can restyle HUMAN's) keeps the captcha
    // mount point and its success callback, on a refusal, with HUMAN's app id.
    // A login form with the widget, or a page that only loads the sensor
    // snippet, is none of those.
    applies: (p) =>
      (p.status === 403 || p.status === 429) &&
      p.smallerThan(DENY_PAGE_TEXT * 2) &&
      PERIMETERX_CAPTCHA_ELEMENT.test(p.markup()) &&
      PERIMETERX_APP_ID.test(p.markup()),
  },
  {
    provider: "kasada",
    signal: "Kasada challenge script on a near-empty page",
    applies: (p) =>
      (isStatus(p, WAF_CHALLENGE_STATUS_CODES) || p.status === 202) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      KASADA_MARKER.test(p.markup()),
  },
  {
    provider: "aws-waf",
    signal: "x-amzn-waf-action header",
    applies: (p) => /^(?:challenge|captcha)$/i.test(p.header("x-amzn-waf-action") ?? ""),
  },
  {
    provider: "aws-waf",
    signal: "AWS WAF challenge script on a near-empty page",
    applies: (p) =>
      [202, 401, 403, 405, 429].includes(p.status) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      AWS_WAF_SCRIPT.test(p.markup()),
  },
  {
    provider: "imperva",
    signal: "Imperva incident id on a block page",
    applies: (p) => IMPERVA_INCIDENT_LINE.test(p.text()),
  },
  {
    provider: "imperva",
    signal: 'Imperva interstitial ("Pardon Our Interruption")',
    applies: (p) =>
      isStatus(p, WAF_BLOCK_STATUS_CODES) &&
      p.smallerThan(INTERSTITIAL_TEXT * 2) &&
      IMPERVA_PARDON_TITLE.test(p.text()) &&
      IMPERVA_PARDON_BODY.test(p.text()),
  },
  {
    provider: "imperva",
    signal: "Imperva JavaScript challenge page with no content",
    applies: (p) =>
      isStatus(p, REFUSAL_STATUS_CODES) &&
      p.smallerThan(EMPTY_PAGE_TEXT) &&
      IMPERVA_SCRIPT.test(p.markup()),
  },
  {
    provider: "f5",
    signal: 'F5 rejection page ("The requested URL was rejected")',
    applies: (p) =>
      isStatus(p, WAF_BLOCK_STATUS_CODES) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      F5_REJECTED.test(p.text()) &&
      F5_SUPPORT_ID.test(p.text()),
  },
  {
    provider: "radware",
    signal: "Radware Bot Manager captcha host on a near-empty page",
    applies: (p) =>
      isStatus(p, REFUSAL_STATUS_CODES) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      RADWARE_HOST.test(p.markup()),
  },
  {
    provider: "sucuri",
    signal: 'Sucuri firewall "Access Denied" page',
    applies: (p) => SUCURI_BLOCK.some((pattern) => pattern.test(p.text())),
  },
  {
    provider: "wordfence",
    signal: "Wordfence block page",
    applies: (p) =>
      [403, 406, 429, 503].includes(p.status) &&
      p.smallerThan(INTERSTITIAL_TEXT * 4) &&
      WORDFENCE_FOOTER.test(p.text()) &&
      WORDFENCE_HEADING.test(p.text()) &&
      WORDFENCE_TIME_SCRIPT.test(p.markup()),
  },
  {
    provider: "akamai",
    signal: 'Akamai "Access Denied" page with a reference number',
    applies: (p) =>
      isStatus(p, WAF_BLOCK_STATUS_CODES) &&
      p.smallerThan(DENY_PAGE_TEXT) &&
      AKAMAI_DENY_TITLE.test(p.text()) &&
      (AKAMAI_ENTITY_REFERENCE.test(p.text()) || AKAMAI_REFERENCE_ID.test(p.text())),
  },
  {
    provider: "vercel",
    signal: "x-vercel-mitigated header",
    applies: (p) => /^(?:challenge|deny)$/i.test(p.header("x-vercel-mitigated") ?? ""),
  },
  {
    provider: "vercel",
    signal: "Vercel Security Checkpoint page",
    applies: (p) =>
      [403, 429, 503].includes(p.status) &&
      p.smallerThan(INTERSTITIAL_TEXT) &&
      VERCEL_CHECKPOINT.test(p.text()),
  },
  {
    provider: "cloudflare",
    signal: "cf-mitigated: challenge header",
    applies: (p) => /^challenge$/i.test(p.header("cf-mitigated") ?? ""),
  },
  {
    provider: "cloudflare",
    signal: "Cloudflare challenge script",
    // Only a challenge loads the orchestrate script or sets these options; the
    // JavaScript Detections script every protected page loads is not matched.
    applies: (p) => CLOUDFLARE_CHALLENGE_MARKUP.some((pattern) => pattern.test(p.markup())),
  },
  {
    provider: "cloudflare",
    signal: 'Cloudflare block page ("Attention Required!")',
    applies: (p) =>
      [401, 403, 429, 503].includes(p.status) &&
      CLOUDFLARE_BLOCK_TITLE.test(p.text()) &&
      (CLOUDFLARE_BLOCK_MARKER.test(p.markup()) || CLOUDFLARE_RAY_LINE.test(p.text())),
  },
];

function probeFor(response: WafResponse): Probe {
  const full = response.html ?? "";
  const html = full.slice(0, SCAN_BYTES);
  // Only the first 32 KB is read, so a huge page whose head is heavy markup
  // would look near-empty. No interstitial is that large.
  const tooBigToBeAnInterstitial = full.length > MAX_INTERSTITIAL_BYTES;
  let views: ReturnType<typeof signatureViews> | null = null;
  const read = () => (views ??= signatureViews(html));
  const small = new Map<number, boolean>();
  return {
    status: response.status,
    header: (name) => headerValue(response.headers.raw, name),
    markup: () => (html === "" ? "" : read().markup),
    text: () => (html === "" ? "" : read().text),
    smallerThan: (limit) => {
      if (tooBigToBeAnInterstitial) return false;
      let known = small.get(limit);
      if (known === undefined) {
        known = visibleTextLength(html, limit) <= limit;
        small.set(limit, known);
      }
      return known;
    },
  };
}

const CLEAR: WafBlockResult = { verdict: "clear", providerId: null, provider: null, signal: null };

/**
 * Whether a response is a perimeter provider's challenge or block page.
 *
 * `blocked` is high confidence: a provider-specific header, or a
 * provider-specific marker with the status and body shape its block page has.
 * A page that only mentions a vendor, loads its script, or carries a CAPTCHA
 * widget on a form is `clear`. `suspect` is a refusal-shaped page from a known
 * provider with no provider block marker (a bare "Access Denied"): the caller
 * warns and still audits it.
 */
export function classifyWafResponse(response: WafResponse): WafBlockResult {
  const probe = probeFor(response);
  for (const rule of RULES) {
    if (rule.applies(probe)) {
      return {
        verdict: "blocked",
        providerId: rule.provider,
        provider: getWafProviderName(rule.provider),
        signal: rule.signal,
      };
    }
  }

  if (WAF_CHALLENGE_STATUS_CODES.has(response.status) || response.status === 406) {
    const raw = response.headers.raw;
    const headers = new Headers();
    for (const [name, value] of [
      ["server", response.headers.server],
      ["cf-cache-status", response.headers.cfCacheStatus],
      ["x-cache", response.headers.xCache],
    ] as const) {
      if (value) headers.set(name, value);
    }
    if (raw) {
      for (const name of [
        "cf-ray",
        "x-akamai-request-id",
        "x-datadome",
        "x-dd-b",
        "x-sucuri-id",
        "x-iinfo",
      ]) {
        const value = headerValue(raw, name);
        if (value !== null) headers.set(name, value);
      }
    }
    const waf = detectWafFromHeaders(headers);
    if (waf.detected && waf.provider && waf.confidence === "high") {
      const text = probe.text();
      if (probe.smallerThan(INTERSTITIAL_TEXT) && REFUSAL_WORDING.test(text.slice(0, 4096))) {
        return {
          verdict: "suspect",
          providerId: waf.provider,
          provider: getWafProviderName(waf.provider),
          signal: `refusal page from ${getWafProviderName(waf.provider)} with no provider block marker`,
        };
      }
    }
  }
  return CLEAR;
}
