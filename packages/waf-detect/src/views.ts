/**
 * Two readings of a page's opening HTML for body signatures (#693), so a page
 * that QUOTES a provider's signature is not attributed to the provider.
 *
 * - `markup`: where a script or resource signature acts. Every tag with its
 *   attributes, and the body of each inline `<script>`. Text is left out, so an
 *   escaped `&lt;script src="https://js.datadome.co/tags.js"&gt;` in a tutorial
 *   is not DataDome. Hyperlink tags (`<a>`, `<area>`) are left out too: a link
 *   to a provider's script is a mention.
 * - `text`: where block-page wording appears. The HTML with comments, script
 *   and style bodies, and every `<code>`, `<kbd>`, `<samp>`, `<textarea>` and
 *   `<xmp>` element removed, tags kept: a support page that prints
 *   `Incapsula incident ID: 1234-5678` in a code block is not Imperva. A bare
 *   `<pre>` stays: CloudFront's own block page prints its "Generated by
 *   cloudfront" footer in one. The `<pre><code>` that Markdown and syntax
 *   highlighters emit is removed by its `<code>`.
 *
 * Linear in the input: one pass, each raw-text body skipped with one search.
 */
export interface SignatureViews {
  markup: string;
  text: string;
}

/** Elements whose content a page uses to quote code or sample output. */
const QUOTE_ELEMENTS = new Set(["code", "kbd", "samp"]);

/**
 * Block-level end tags that close any quote element still open inside them, as
 * the HTML parser closes an unclosed `<code>` at its parent's end (pub#904): a
 * stray `<code>` must not hide a block page's wording for the rest of the page.
 */
const QUOTE_CLOSING_BLOCKS = new Set([
  "address", "article", "aside", "blockquote", "body", "dd", "div", "dl", "dt", "figure",
  "footer", "form", "h1", "h2", "h3", "h4", "h5", "h6", "header", "html", "li", "main",
  "nav", "ol", "p", "pre", "section", "table", "td", "th", "tr", "ul",
]);

/**
 * Raw-text and RCDATA elements (HTML Standard 13.2.5): their content is never
 * parsed as tags. `textarea` and `xmp` hold quoted text; `iframe`, `noembed`,
 * `noframes` and `title` hold text a page shows (an iframe's is fallback text,
 * as on Imperva's block page).
 */
const RAW_TEXT_ELEMENTS = new Set(["script", "style", "textarea", "xmp", "iframe", "noembed", "noframes", "title"]);
const RAW_TEXT_SHOWN = new Set(["iframe", "noembed", "noframes", "title"]);

/** The index of the `>` that ends the tag opened before `start`, quotes respected. */
export function tagEnd(html: string, start: number): number {
  let quote: '"' | "'" | null = null;
  for (let i = start; i < html.length; i++) {
    const char = html[i];
    if (quote) {
      if (char === quote) quote = null;
    } else if (char === '"' || char === "'") {
      quote = char;
    } else if (char === ">") {
      return i;
    }
  }
  return html.length - 1;
}

/** Where the raw-text body starting at `from` ends: at its closing tag, or the end. */
function rawTextEnd(lower: string, name: string, from: number): number {
  const prefix = `</${name}`;
  let cursor = from;
  while (cursor < lower.length) {
    const close = lower.indexOf(prefix, cursor);
    if (close < 0) return lower.length;
    const boundary = lower[close + prefix.length];
    if (boundary === undefined || boundary === ">" || boundary === "/" || /\s/.test(boundary)) {
      return close;
    }
    cursor = close + prefix.length;
  }
  return lower.length;
}

/**
 * ASCII-only lowercase, the same length as the input: tag names are ASCII,
 * and `toLowerCase` turns some characters (`İ`) into two, which would shift
 * every offset after them.
 */
function asciiLower(html: string): string {
  return html.replace(/[A-Z]+/g, (run) => run.toLowerCase());
}

export function signatureViews(html: string): SignatureViews {
  const lower = asciiLower(html);
  const markup: string[] = [];
  const text: string[] = [];
  // Open quote elements: `<pre><code>` nests, and a stray close tag does not
  // go below zero.
  let quoteDepth = 0;
  // Blocks opened inside the open quote, so a block nested in a `<code>`
  // closes itself and not the quote around it.
  let blocksInQuote = 0;
  let cursor = 0;

  while (cursor < html.length) {
    const lt = html.indexOf("<", cursor);
    const textEnd = lt < 0 ? html.length : lt;
    if (textEnd > cursor && quoteDepth === 0) text.push(html.slice(cursor, textEnd));
    if (lt < 0) break;

    if (lower.startsWith("<!--", lt)) {
      const end = lower.indexOf("-->", lt + 4);
      cursor = end < 0 ? html.length : end + 3;
      text.push(" ");
      continue;
    }

    const closing = html[lt + 1] === "/";
    const nameStart = lt + (closing ? 2 : 1);
    let nameEnd = nameStart;
    while (/[a-z0-9-]/.test(lower[nameEnd] ?? "")) nameEnd++;
    const name = lower.slice(nameStart, nameEnd);
    if (!/^[a-z]/.test(name)) {
      // A `<` that opens no tag is text.
      if (quoteDepth === 0) text.push("<");
      cursor = lt + 1;
      continue;
    }

    const end = tagEnd(html, nameEnd);
    const tag = html.slice(lt, end + 1);
    cursor = end + 1;

    if (quoteDepth > 0 && QUOTE_CLOSING_BLOCKS.has(name)) {
      if (!closing) blocksInQuote++;
      else if (blocksInQuote > 0) blocksInQuote--;
      else quoteDepth = 0;
    }
    if (QUOTE_ELEMENTS.has(name)) {
      quoteDepth = closing ? Math.max(0, quoteDepth - 1) : quoteDepth + 1;
      if (quoteDepth === 0) blocksInQuote = 0;
      text.push(" ");
      continue;
    }
    if (name !== "a" && name !== "area") markup.push(tag);
    if (quoteDepth === 0) text.push(tag);

    // A raw-text element never self-closes in HTML: `<script/>` opens one.
    if (!closing && RAW_TEXT_ELEMENTS.has(name)) {
      const body = rawTextEnd(lower, name, cursor);
      const content = html.slice(cursor, body);
      if (name === "script") markup.push(content);
      else if (RAW_TEXT_SHOWN.has(name) && quoteDepth === 0) text.push(content);
      // The closing tag is read on the next turn, like any other tag.
      cursor = body;
    }
  }

  return { markup: markup.join(" "), text: text.join("") };
}
