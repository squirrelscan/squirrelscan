import type { Detector, TechFingerprint } from "../types";
import { resourceAttr, scriptSrc } from "./helpers";

// WordPress plugins and managed WordPress hosts (#1033).
//
// A plugin is recognised by something it writes into the page: an asset URL under
// `wp-content/plugins/<slug>/` (or the cache directory it fills), or the HTML
// comment or schema block it emits. Never by its name in page text: every
// markup detector needs a script tag, a resource attribute or a literal `<!--`,
// so a blog post about WP Rocket or a `<pre>` sample does not match. These
// fingerprints leave `ignoreComments` off on purpose, because the comment IS the
// signal.
//
// A host is recognised by the response header it sets; its fingerprint lists the
// header first, so `detectedBy` reads `header:<name>`.

/**
 * An asset URL under `wp-content/<dir>/`, as a script URL, a script `src`, or a
 * `link`, `img` or `source` attribute (never an `<a href>`). `dirs` are regex
 * source fragments such as `plugins\/wp-rocket`. The prefix before `wp-content`
 * is bounded, so a hostile URL cannot make the scan superlinear.
 */
function wpAssets(dirs: string[]): Detector[] {
  const url = String.raw`(?:(?:https?:)?\/\/[^\/"'\s]{1,200})?\/(?:[^"'\s?#]{0,200}\/)?wp-content\/(?:${dirs.join("|")})\/`;
  return [...scriptSrc(url), resourceAttr("link|img|source", "href|src|srcset|data-src", url)];
}

/** A literal HTML comment, opened at `<!--` (the gate keeps the scan to pages that have one). */
function comment(source: string): Detector {
  return { type: "html", requires: "<!--", pattern: new RegExp(`<!--\\s*${source}`, "i") };
}

/** A JSON-LD block tagged with the plugin's own class. */
function schemaBlock(requires: string, className: string = requires): Detector {
  return {
    type: "html",
    requires,
    pattern: new RegExp(
      `<script\\s(?:[^>]{0,300}\\s)?type\\s*=\\s*["']application\\/ld\\+json["'](?:[^>]{0,300}\\s)?class\\s*=\\s*["']${className}["']`,
      "i",
    ),
  };
}

