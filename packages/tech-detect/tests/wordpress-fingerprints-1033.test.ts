// WordPress caching, SEO and image plugins and managed WordPress hosts (#1033).

import { describe, expect, test } from "bun:test";

import { ALL_FINGERPRINTS } from "../src/fingerprints";
import { detectTechnologies } from "../src/detect";
import { WORDPRESS_FINGERPRINTS } from "../src/fingerprints/wordpress";
import type { TechDetectInput } from "../src/types";

const input = (partial: Partial<TechDetectInput>): TechDetectInput => ({
  url: "https://example.com/",
  headers: {},
  html: "",
  ...partial,
});
const found = (i: TechDetectInput) => detectTechnologies(i);
const ids = (i: TechDetectInput) => found(i).map((t) => t.id);
const ALL_IDS = WORDPRESS_FINGERPRINTS.map((f) => f.id);

// A plain WordPress page: the theme, core scripts and the REST link, no plugin of the lot.
const PLAIN_WP = `<!doctype html><html lang="en-US"><head><meta charset="UTF-8">
<title>A plain WordPress site</title><meta name="generator" content="WordPress 6.6">
<link rel="stylesheet" href="https://example.com/wp-content/themes/twentytwentyfour/style.css">
<link rel="https://api.w.org/" href="https://example.com/wp-json/"></head>
<body><h1>Hello</h1><script src="https://example.com/wp-includes/js/jquery/jquery.min.js"></script></body></html>`;

// A post that talks about every plugin and host, with the markup shown escaped.
const BLOG = `<!doctype html><html><head><title>WP Rocket vs LiteSpeed Cache vs W3 Total Cache</title></head><body>
<p>We tried WP Rocket, LiteSpeed Cache, W3 Total Cache, WP Super Cache, WP Fastest Cache, Autoptimize and Perfmatters.
Yoast SEO, Rank Math, All in One SEO and SEOPress compared. ShortPixel, Imagify, EWWW Image Optimizer and Smush too.
Hosting on WP Engine, Kinsta, Pressable, WordPress VIP, SiteGround or Cloudways: wp-content/plugins/wp-rocket/ is where it lives.</p>
<pre>&lt;!-- This website is like a Rocket, isn't it ? Performance optimized by WP Rocket --&gt;
&lt;script src="https://example.com/wp-content/plugins/wordpress-seo/js/x.js"&gt;&lt;/script&gt;
&lt;script type="application/ld+json" class="yoast-schema-graph"&gt;{}&lt;/script&gt;</pre>
<p>Send the header x-kinsta-cache and x-litespeed-cache, or X-Powered-By: WP Engine.</p></body></html>`;

describe("WordPress plugin and host fingerprints (#1033)", () => {
  test("every one has a category from the new set and an icon slug", () => {
    for (const fp of WORDPRESS_FINGERPRINTS) {
      expect(["cache", "seo", "images", "hosting"]).toContain(fp.category);
      expect(fp.icon).toBeTruthy();
      expect(ALL_FINGERPRINTS).toContain(fp);
    }
    expect(WORDPRESS_FINGERPRINTS).toHaveLength(21);
  });

  test("a plain WordPress page matches none of them", () => {
    expect(ids(input({ html: PLAIN_WP })).filter((id) => ALL_IDS.includes(id))).toEqual([]);
    expect(ids(input({ html: PLAIN_WP }))).toContain("wordpress");
  });

  test("a post that only names them, with the markup shown in <pre>, matches none", () => {
    expect(ids(input({ html: BLOG })).filter((id) => ALL_IDS.includes(id))).toEqual([]);
  });

  describe("detected from the asset URL or the plugin's own markup", () => {
    const comment = (text: string) => `${PLAIN_WP}<!-- ${text} -->`;
    const asset = (path: string) =>
      PLAIN_WP.replace(
        "</head>",
        `<link rel="stylesheet" href="https://example.com/wp-content/${path}"></head>`,
      );
    const script = (path: string) => `${PLAIN_WP}<script src="/wp-content/${path}"></script>`;

    test.each([
      [
        "wp-rocket",
        comment(
          "This website is like a Rocket, isn't it ? Performance optimized by WP Rocket. Learn more: https://wp-rocket.me",
        ),
      ],
      ["wp-rocket", asset("cache/wp-rocket/example.com/index.html")],
      ["wp-rocket", asset("cache/min/1/wp-content/themes/x/style.css")],
      [
        "litespeed-cache",
        comment("Page generated by LiteSpeed Cache 6.5.0.1 on 2025-01-01 10:00:00 -->"),
      ],
      ["litespeed-cache", asset("plugins/litespeed-cache/assets/css/x.css")],
      [
        "w3-total-cache",
        comment(
          "Performance optimized by W3 Total Cache. Learn more: https://www.boldgrid.com/w3-total-cache/",
        ),
      ],
      ["w3-total-cache", asset("cache/minify/abc12.css")],
      ["wp-super-cache", comment("Cached page generated by WP-Super-Cache on 2025-01-01 10:00:00")],
      [
        "wp-fastest-cache",
        comment("WP Fastest Cache file was created in 0.123 seconds, on 01-01-25 10:00:00"),
      ],
      ["wp-fastest-cache", asset("cache/wpfc-minified/abc/style.css")],
      ["autoptimize", asset("cache/autoptimize/css/autoptimize_abc.css")],
      ["perfmatters", script("plugins/perfmatters/js/lazyload.min.js")],
      [
        "yoast-seo",
        comment(
          "This site is optimized with the Yoast SEO plugin v23.5 - https://yoast.com/wordpress/plugins/seo/",
        ),
      ],
      [
        "yoast-seo",
        `${PLAIN_WP}<script type="application/ld+json" class="yoast-schema-graph">{"@graph":[]}</script>`,
      ],
      ["rank-math", comment("Search Engine Optimization by Rank Math - https://rankmath.com/")],
      [
        "rank-math",
        `${PLAIN_WP}<script type="application/ld+json" class="rank-math-schema">{}</script>`,
      ],
      ["all-in-one-seo", comment("All in One SEO 4.7.1 - aioseo.com")],
      [
        "all-in-one-seo",
        `${PLAIN_WP}<script type="application/ld+json" class="aioseo-schema">{}</script>`,
      ],
      ["seopress", asset("plugins/wp-seopress/assets/css/x.css")],
      ["shortpixel", asset("plugins/shortpixel-image-optimiser/res/css/x.css")],
      [
        "shortpixel",
        `${PLAIN_WP}<img src="https://cdn.shortpixel.ai/spai/w_400+q_lossy+ret_img/example.com/a.jpg" alt="">`,
      ],
      ["imagify", asset("plugins/imagify/assets/css/x.css")],
      ["ewww-image-optimizer", script("plugins/ewww-image-optimizer/includes/lazysizes.min.js")],
      ["smush", script("plugins/wp-smushit/app/assets/js/smush-lazy-load.min.js")],
    ])("%s", (id, html) => {
      expect(ids(input({ html }))).toContain(id);
    });

    test("a plugin asset URL is found in the script list too, relative to the host", () => {
      const url = "https://example.com/wp-content/plugins/perfmatters/js/x.js";
      expect(ids(input({ html: PLAIN_WP, scripts: [{ url }] }))).toContain("perfmatters");
    });

    test("a plugin path in an <a href> or in prose is not an install", () => {
      const html = `${PLAIN_WP}<a href="https://example.com/wp-content/plugins/wp-rocket/readme.txt">readme</a><p>see /wp-content/plugins/wp-rocket/ here</p>`;
      expect(ids(input({ html }))).not.toContain("wp-rocket");
    });

    test("versions come from the comment", () => {
      const hit = (id: string, html: string) => found(input({ html })).find((t) => t.id === id);
      expect(
        hit(
          "yoast-seo",
          comment("This site is optimized with the Yoast SEO plugin v23.5 - https://yoast.com/"),
        )?.version,
      ).toBe("23.5");
      expect(
        hit("litespeed-cache", comment("Page generated by LiteSpeed Cache 6.5.0.1 on x"))?.version,
      ).toBe("6.5.0.1");
      expect(hit("all-in-one-seo", comment("All in One SEO 4.7.1 - aioseo.com"))?.version).toBe(
        "4.7.1",
      );
    });
  });

  describe("managed hosts from response headers", () => {
    test.each([
      ["wp-engine", { "x-powered-by": "WP Engine" }, "header:x-powered-by"],
      ["wp-engine", { server: "WP Engine" }, "header:server"],
      ["kinsta", { "x-kinsta-cache": "HIT" }, "header:x-kinsta-cache"],
      ["pressable", { "x-powered-by": "Pressable" }, "header:x-powered-by"],
      ["wordpress-vip", { "x-powered-by": "WordPress.com VIP" }, "header:x-powered-by"],
      ["siteground", { "x-sg-cache": "HIT" }, "header:x-sg-cache"],
      ["cloudways", { server: "Cloudways" }, "header:server"],
      ["litespeed-cache", { "x-litespeed-cache": "hit" }, "header:x-litespeed-cache"],
      ["w3-total-cache", { "x-powered-by": "W3 Total Cache/2.7.5" }, "header:x-powered-by"],
    ])("%s from %j records %s", (id, headers, detectedBy) => {
      const hit = found(input({ headers, html: PLAIN_WP })).find((t) => t.id === id);
      expect(hit?.detectedBy).toBe(detectedBy);
    });

    test("a plain WordPress page on plain headers matches no host", () => {
      const headers = { server: "nginx", "x-powered-by": "PHP/8.2.0" };
      expect(ids(input({ headers, html: PLAIN_WP })).filter((id) => ALL_IDS.includes(id))).toEqual(
        [],
      );
    });

    test("look-alike header values do not match", () => {
      expect(ids(input({ headers: { "x-powered-by": "Not WP Engineered" } }))).not.toContain(
        "wp-engine",
      );
      expect(ids(input({ headers: { server: "kinsta-fake.example" } }))).not.toContain("kinsta");
    });
  });
});

describe("bolt-new (#1278)", () => {
  test("a bolt.host app, any depth up to three labels", () => {
    expect(ids(input({ url: "https://my-app.bolt.host/" }))).toContain("bolt-new");
    expect(ids(input({ url: "https://a.b.bolt.host/x?y=1" }))).toContain("bolt-new");
    expect(
      found(input({ url: "https://my-app.bolt.host/" })).find((t) => t.id === "bolt-new"),
    ).toMatchObject({
      name: "Bolt",
      category: "cms",
      detectedBy: expect.stringContaining("url-path"),
    });
  });

  test("the Made in Bolt badge on a custom domain", () => {
    const html = `<footer><a href="https://bolt.new/?rid=abc123" target="_blank"><img src="/badge.svg" alt="Made in Bolt"></a></footer>`;
    expect(ids(input({ url: "https://studio.example.com/", html }))).toContain("bolt-new");
  });

  test("look-alike hosts, links to a bolt.host app and prose do not match", () => {
    for (const url of [
      "https://bolt.host.attacker.example/",
      "https://notbolt.host/",
      "https://my-app.bolt.hosting/",
      "https://bolt.host/",
    ]) {
      expect(ids(input({ url }))).not.toContain("bolt-new");
    }
    const html = `<a href="https://my-app.bolt.host/">demo</a><p>Built with bolt.new and hosted on bolt.host. Visit https://bolt.new/?rid=abc123</p>
<pre>&lt;a href="https://bolt.new/?rid=abc123"&gt;x&lt;/a&gt;</pre>`;
    expect(ids(input({ url: "https://blog.example.com/", html }))).not.toContain("bolt-new");
  });

  test("bolt-payments and bolt-new do not cross-match", () => {
    const checkout = `<script src="https://connect.bolt.com/connect-bolt.js"></script><script>BoltCheckout.configure({})</script>`;
    const checkoutIds = ids(
      input({
        url: "https://shop.example.com/cart",
        html: checkout,
        scripts: [{ url: "https://connect.bolt.com/connect-bolt.js" }],
      }),
    );
    expect(checkoutIds).toContain("bolt-payments");
    expect(checkoutIds).not.toContain("bolt-new");
    const app = ids(input({ url: "https://my-app.bolt.host/" }));
    expect(app).toContain("bolt-new");
    expect(app).not.toContain("bolt-payments");
  });
});
